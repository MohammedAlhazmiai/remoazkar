    fun byCategory(category: String): List<RuqyahItem> = items.filter { it.category == category }

    fun categories(): List<String> = listOf(CAT_QURAN, CAT_SUNNAH, CAT_GUIDE)

    fun item(id: Int): RuqyahItem? = items.firstOrNull { it.id == id }

    /** النص الكامل لقسم ما، لقراءته بالروبوت دفعة واحدة. */
    fun fullText(category: String): String = byCategory(category).joinToString(separator = " ") { item ->
        val repeatPart = if (item.repeat > 1) " تُقرأ ${item.repeat} مرات." else ""
        "${item.title}. ${item.text}.$repeatPart"
    }
