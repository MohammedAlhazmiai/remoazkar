    /**
     * يتحقق هل الاستعلام يقع ضمن الاختصاص الديني الإسلامي أم أنه خارج النطاق.
     * يُرجع true إذا كان دينيًا مقبولًا، وfalse إذا كان دنيويًا خارج الاختصاص ويجب الاعتذار عنه.
     */
    fun isAllowedQuery(rawQuery: String, hasPriorContext: Boolean = false): Boolean {
        val norm = ArabicNlpEngine.normalize(rawQuery)
        if (norm.isBlank()) return true // التحيات والافتتاحيات تقع ضمن التهيئة العامة

        // 1. فحص مصطلحات الرفض الدنيوية الصريحة
        for (rejectTerm in SECULAR_REJECT_TERMS) {
            val normalizedReject = ArabicNlpEngine.normalize(rejectTerm)
            if (norm.contains(normalizedReject)) {
                // إذا كان السؤال يسأل عن الحكم الشرعي لهذه المسألة (مثل: ما حكم لعب البلايستيشن، أو حكم التداول)
                val isAskingFiqhRuling = norm.contains("ما حكم") || norm.contains("هل يجوز") ||
                    norm.contains("حكم الشرع") || norm.contains("فتوى") || norm.contains("فتوي") ||
                    norm.contains("حلال ام حرام") || norm.contains("في الاسلام") || norm.contains("شرعا")
                if (!isAskingFiqhRuling) {
                    return false
                }
            }
        }

        // 2. التحقق من وجود كلمات مفتاحية دينية صريحة في النص بعد توحيد الحروف
        val hasDirectKeyword = ISLAMIC_KEYWORD_SIGNALS.any { signal ->
            norm.contains(signal)
        }
        if (hasDirectKeyword) return true

        // 3. التحقق من وجود جذور إسلامية معتمدة عبر محلل الجذور
        val indexed = ArabicNlpEngine.indexText(norm)
        val hasIslamicStem = indexed.stems.any { stem ->
            stem in ISLAMIC_KEYWORD_SIGNALS || ISLAMIC_KEYWORD_SIGNALS.any { signal -> stem.contains(signal) || signal.contains(stem) }
        }
        if (hasIslamicStem) return true

        // 4. التحقق من صيغ الأسئلة والطلبات الدينية والشرعية الشائعة
        val isReligiousQuestionFormat = norm.startsWith("ما حكم") || norm.startsWith("هل يجوز") ||
            norm.startsWith("كيف اصلي") || norm.startsWith("كيف اتوضا") || norm.startsWith("ما تفسير") ||
            norm.startsWith("اكتب لي دعاء") || norm.startsWith("اكتب خطبه") || norm.startsWith("اكتب رساله") ||
            norm.startsWith("اكتب خاطره") || norm.startsWith("صمم بطاقه") || norm.startsWith("صمم صوره") ||
            norm.contains("في الاسلام") || norm.contains("شرعا") || norm.contains("عند اهل السنه") ||
            norm.contains("وفق الشرع") || norm.contains("حكم الصلاه") || norm.contains("في المنام")

        if (isReligiousQuestionFormat) return true

        // 5. التحية والسلام والشكر والأدعية القصيرة ومتابعة السياق مقبولة دائمًا
        val isGreetingOrThanksOrFollowUp = norm.contains("سلام") || norm.contains("مرحبا") ||
            norm.contains("اهلا") || norm.contains("جزاك") || norm.contains("شكرا") ||
            norm.contains("بارك") || norm.contains("امين") || norm.contains("اختصر") ||
            norm.contains("لخص") || norm.contains("دليل") || norm.contains("شاهد") ||
            norm.contains("اكمل") || norm.contains("واصل") || norm.contains("وضح")
        if (isGreetingOrThanksOrFollowUp) return true

        // 6. إذا كان هناك سياق محادثة سابق، نسمح بالردود التتابعية الوجيزة
        if (hasPriorContext && indexed.tokens.size <= 4) return true

        // إذا كان السؤال خاليًا تمامًا من أي دلالة دينية وكلماته عامة، نعتذر عنه
        return indexed.tokens.size <= 1
    }
