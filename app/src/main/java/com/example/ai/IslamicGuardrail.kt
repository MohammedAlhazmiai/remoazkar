    fun isAllowedQuery(rawQuery: String, hasPriorContext: Boolean = false): Boolean {
        val norm = ArabicNlpEngine.normalize(rawQuery)
        if (norm.isBlank()) return true

        val isDreamContext = norm.contains("حلم") || norm.contains("حلمت") || norm.contains("منام") || norm.contains("رويا")
        val isAskingFiqhRuling = norm.contains("ما حكم") || norm.contains("هل يجوز") ||
            norm.contains("حكم الشرع") || norm.contains("فتوي") || norm.contains("فتوى") ||
            norm.contains("حلال ام حرام") || norm.contains("في الاسلام") || norm.contains("شرعا")

        // 1. فحص مصطلحات الرفض الدنيوية الصريحة
        for (rejectTerm in SECULAR_REJECT_TERMS) {
            val normalizedReject = ArabicNlpEngine.normalize(rejectTerm)
            if (norm.contains(normalizedReject)) {
                if (!isAskingFiqhRuling && !isDreamContext) {
                    return false
                }
            }
        }

        // 2. التحقق من وجود كلمات مفتاحية دينية صريحة
        if (ISLAMIC_KEYWORD_SIGNALS.any { norm.contains(it) }) return true

        // 3. التحقق من مؤشرات الدردشة الأخوية اليومية المباحة
        if (FRIENDLY_DAILY_CHAT_SIGNALS.any { norm.contains(it) }) return true

        // 4. التحقق من وجود جذور إسلامية معتمدة
        val indexed = ArabicNlpEngine.indexText(norm)
        val hasIslamicStem = indexed.stems.any { stem ->
            stem in ISLAMIC_KEYWORD_SIGNALS || ISLAMIC_KEYWORD_SIGNALS.any { signal -> stem.contains(signal) || signal.contains(stem) }
        }
        if (hasIslamicStem) return true

        // 5. صيغ الأسئلة والطلبات الدينية الشائعة
        val isReligiousQuestionFormat = norm.startsWith("ما حكم") || norm.startsWith("هل يجوز") ||
            norm.startsWith("هل لي") || norm.startsWith("كم ركعه") || norm.startsWith("ما عدد") ||
            norm.startsWith("ما فضل") || norm.startsWith("كيف اصلي") || norm.startsWith("كيف اصوم") ||
            norm.startsWith("كيف احج") || norm.startsWith("كيف اتوضا") || norm.startsWith("كيف استغفر") ||
            norm.startsWith("ماذا اقول") || norm.startsWith("بم تنصح") || norm.startsWith("ما تفسير") ||
            norm.startsWith("رايت") || norm.startsWith("حلمت") ||
            norm.startsWith("اكتب لي دعاء") || norm.startsWith("اكتب خطبه") || norm.startsWith("اكتب رساله") ||
            norm.startsWith("اكتب خاطره") || norm.startsWith("اكتب محاضره") ||
            norm.startsWith("صمم بطاقه") || norm.startsWith("صمم صوره") ||
            norm.contains("في الاسلام") || norm.contains("في القران") || norm.contains("في السنه") ||
            norm.contains("في الفقه") || norm.contains("شرعا") || norm.contains("عند اهل السنه") ||
            norm.contains("وفق الشرع") || norm.contains("حكم الصلاه") || norm.contains("في المنام")
        if (isReligiousQuestionFormat) return true

        // 6. إذا كان هناك سياق محادثة سابق، نسمح بالردود التتابعية الوجيزة
        if (hasPriorContext && indexed.tokens.size <= 5) return true

        return indexed.tokens.size <= 1
    }
