                )

            // 3. رد المستخدم بأنه بخير
            (norm == "بخير" || norm == "تمام" || norm == "كويس" || norm.contains("الحمد لله بخير") ||
                norm.contains("الحمد لله تمام") || norm.contains("ماشي الحال") || norm.contains("طيب الحمد لله")) ->
                DailyChatReply(
                    text = "عساها دوم يا رب في صحة وعافية ورضا! من سُرّ بما قسم الله عاش هنيّ البال.\n\n" +
                        "لو حاب تشاركني وش خطتك لبقية اليوم، أو تحب نختار ذكرًا خفيفًا يبارك لك في وقتك، أنا معك يا صديقي.",
                    domainTag = "دردشة أخوية يومية",
                    detectedTopic = "مشاركة السرور والحمد",
                    followUps = listOf("أعطني دعاءً للبركة في الوقت", "نسولف شوي")
                )

            // 4. الأخبار السعيدة والنجاح (يُفحص قبل ضغط الدراسة/الاختبارات حتى لا يُعزّى الناجح بتعب الاختبار)
            norm.contains("نجحت") || norm.contains("فرحان") || norm.contains("مبسوط") ||
                norm.contains("تخرجت") || norm.contains("ترقيت") || norm.contains("توفقت") || norm.contains("ابشرك") ->
                DailyChatReply(
                    text = "ما شاء الله تبارك الله! ألف ألف مبارك يا غالي، والله فرحت لك من كل قلبي كأنه لي!\n\n" +
                        "أكرمك الله وزادك من فضله، وقيد النعمة بالشكر؛ قل من قلبك: «الحمد لله الذي بنعمته تتم الصالحات» وأسجد لوجهه شكرًا إن تيسّر.\n" +
                        "شاركني فرحتك: وش هذا الخبر الطيب اللي أسعدك اليوم؟",
                    domainTag = "دردشة أخوية يومية",
                    detectedTopic = "مشاركة الفرح والتهنئة",
                    followUps = listOf("اكتب لي دعاء شكر النعمة", "اكتب رسالة تهنئة ومشاركة فرح")
                )

            // 5. تعب العمل أو الدراسة وضغوط اليوم
            norm.contains("تعبان") || norm.contains("متعب") || norm.contains("مرهق") ||
                norm.contains("مضغوط") || norm.contains("الشغل") || norm.contains("العمل") ||
                norm.contains("الدوام") || norm.contains("الدراسه") || norm.contains("امتحان") || norm.contains("اختبار") ->
                DailyChatReply(
                    text = "الله يعينك ويهوّن عليك يا صديقي! والله مقدّر قد إيش الشغل وضغط اليوم يهدّون الحيل.\n\n" +
                        "خذ نفسًا عميقًا وريّح نفسك لو عشر دقايق بكوب ماء دافئ أو استرخاء، ولا تحمّل قلبك فوق طاقته؛ فأنت تؤجر على سعيك وصبرك على طلب الرزق الحلال أو العلم النافع.\n" +
                        "ردّد بسكينة: «لا حول ولا قوة إلا بالله»، وادعُ: «اللهم إني أبرأ من حولي وقوتي إلى حولك وقوتك».\n\n" +
                        "فضفض لي: وش اللي أرهقك اليوم بالذات؟",
                    domainTag = "دردشة أخوية يومية",
                    detectedTopic = "مواساة صديق في تعب اليوم",
