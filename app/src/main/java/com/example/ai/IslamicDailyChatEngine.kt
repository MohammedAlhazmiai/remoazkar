                DailyChatReply(
                    text = "أحبك الله الذي أحببتني فيه يا أخي الغالي! والله إن الأخوّة الصادقة في الله من أجمل نعم الدنيا.",
                    domainTag = "دردشة أخوية يومية",
                    detectedTopic = "المودة الأخوية",
                    followUps = listOf("دردشة يومية", "اكتب رسالة لصديق عزيز")
