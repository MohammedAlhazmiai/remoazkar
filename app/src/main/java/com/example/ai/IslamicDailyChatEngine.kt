    data class DailyChatReply(
        val text: String,
        val domainTag: String,
        val detectedTopic: String,
        val followUps: List<String>
    )

    private val CAPABILITY_SIGNALS = listOf(
        "من انت", "عرفني بنفسك", "ماذا يمكنك", "ماذا تقدر", "وش تقدر", "ايش تقدر", "شو تقدر",
        "ما خدماتك", "ما هي خدماتك", "ما مهامك", "ماذا تقدم", "ما الذي تقدمه",
        "كيف تستطيع مساعدتي", "وش تسوي", "ايش تسوي", "تقدر تساعدني في ايش", "تستطيع مساعدتي"
    )

    private val SPECIFIC_DOMAIN_GUARDS = listOf(
        "حلم", "حلمت", "تفسير حلم", "رؤيا", "رويا", "منام", "كابوس",
        "ما حكم", "هل يجوز", "فتوي", "فتوى", "حكم ", "كفاره", "سجود السهو",
        "صلاه المسافر", "القصر", "الجمع", "بخاخ الربو", "الزكاه", "زكاه",
        "الوضوء", "غسل", "صيام", "رمضان", "خطبه", "محاضره", "خاطره",
        "رساله", "صمم بطاقه", "ولد صوره", "اركان الاسلام", "اركان الصلاه"
    )

    private fun hasSpecificDomainRequest(norm: String): Boolean =
        SPECIFIC_DOMAIN_GUARDS.any { norm.contains(it) }

    /**
     * يُطابق أسئلة الهوية والخدمات والتحيات البسيطة الصرفة فقط، دون ابتلاع الأسئلة المتخصصة.
     */
    fun matchCapabilityOrQuickGreeting(query: String): DailyChatReply? {
        val norm = ArabicNlpEngine.normalize(query)
        if (norm.isBlank()) return null

        // إذا كان النص يحتوي على سؤال محدد (مثل: مرحبا فسر لي حلم ذبح) نتركه يمر لمحرك الفهم/الذكاء التوليدي
        if (hasSpecificDomainRequest(norm)) return null

        if (CAPABILITY_SIGNALS.any { norm.contains(it) }) {
            return capabilityReply()
        }

        val tokens = norm.split(' ').filter { it.isNotBlank() }
        if (tokens.size <= 4) {
            return when {
                isPureGreeting(norm) -> pureGreetingReply()
                isThanksOrAppreciation(norm) -> thanksReply()
                else -> null
            }
        }
        return null
    }

    /**
