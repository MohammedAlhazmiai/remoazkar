                DailyChatReply(
                    text = "جمعتك طيبة ومباركة يا صديقي، جعلنا الله وإياك ممن صُلّي عليه وأُجيبت دعوته فيها!\nلا تنسَ سورة الكهف والإكثار من الصلاة على النبي ﷺ قبل الغروب.",
                    domainTag = "ترحيب وتعريف",
                    detectedTopic = "تحية يوم الجمعة",
                    followUps = listOf("صمم لي بطاقة جمعة مباركة", "اذكر سنن يوم الجمعة")
                )

            norm.contains("تصبح علي خير") || norm.contains("في امان الله") || norm.contains("مع السلامه") ->
                DailyChatReply(
                    text = "وأنت من أهل الخير والرضا يا صديقي! في حفظ الله وأمانه، ولا تنسَ آية الكرسي والمعوذات قبل النوم.\nألقاك على خير دائمًا!",
