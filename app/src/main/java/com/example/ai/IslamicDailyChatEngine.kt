package com.example.ai

/**
 * محرك التدريب اللغوي المحلي للدردشة اليومية الودية والتعريفية (يعمل 100% بدون إنترنت).
 *
 * - يحاكي حوار صديقين مسلمين بلطف وعفوية ودفء إنساني في الفصحى واللهجات العامية،
 *   مع حارس صارم يمنع ابتلاع الأسئلة العلمية/الدينية المتخصصة (مثل الأحلام أو الفتاوى) عند اقترانها بتحية.
 */
