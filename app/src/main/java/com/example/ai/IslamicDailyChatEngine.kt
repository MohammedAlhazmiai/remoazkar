            // 6. الضيق والحزن والهم والفضفضة
            norm.contains("ضيق") || norm.contains("حزن") || norm.contains("هم") ||
                norm.contains("مهموم") || norm.contains("زعلان") || norm.contains("مكتيب") ||
                norm.contains("قلق") || norm.contains("قلقان") || norm.contains("خايف") ||
                norm.contains("حيران") || norm.contains("مخنوق") || norm.contains("افضفض") || norm.contains("وحيد") ->
                DailyChatReply(
                    text = "سلااامة قلبك يا أخي وصديقي، والله إني أسمعك بقلب حاضر؛ لا تكتم في صدرك ولا تحس أنك وحدك.\n\n" +
                        "أحيانًا الدنيا تضيق علينا من كثر التراكمات، بس تذكّر إن ربك أرحم بك من كل البشر، وقوله حق: ﴿فَإِنَّ مَعَ الْعُسْرِ يُسْرًا ۝ إِنَّ مَعَ الْعُسْرِ يُسْرًا﴾.\n" +
                        "توضّأ وصلِّ ركعتين هادئتين واشكُ لربك كما تشكو لأقرب حبيب، وفضفض لي هنا بما في خاطرك إن ارتحت لذلك، أو خذ هذا الدعاء النبوي: «يا حي يا قيوم برحمتك أستغيث أصلح لي شأني كله ولا تكلني إلى نفسي طرفة عين».",
                    domainTag = "دردشة أخوية يومية",
                    detectedTopic = "مواساة وتفريج الهم",
                    followUps = listOf("ما هو دعاء الكرب والفرج؟", "اكتب خاطرة إيمانية عن جبر الخواطر", "أعطني نصيحة لطمأنينة القلب")
                )

            // 7. الفتور أو التقصير الإيماني
            norm.contains("فتور") || norm.contains("تقصير") || norm.contains("كسل") ||
                norm.contains("ابتعدت عن الله") || norm.contains("ما اخشع") ->
                DailyChatReply(
                    text = "أول علامة حياة قلبك إنك انتبهت لهذا التقصير يا صديقي، وما دامك تبحث عن القرب فالباب مفتوح على مصراعيه.\n\n" +
                        "لا تطلب من نفسك كل شيء دفعة واحدة فتتعب؛ ابدأ اليوم بخطوة صغيرة ثابتة: صلاة بوقتها ولو بأقصر السور، أو صفحتين من المصحف، أو مئة استغفار وأنت تمشي.\n" +
                        "فإن أحب الأعمال إلى الله أدومها وإن قلّ.",
                    domainTag = "دردشة أخوية يومية",
                    detectedTopic = "تشجيع أخوي على الطاعة",
                    followUps = listOf("كيف أبدأ جدولًا بسيطًا للعبادة؟", "اكتب خاطرة عن التوبة والأمل")
                )

            // 8. الغضب أو الخلاف مع صديق أو قريب
            norm.contains("معصب") || norm.contains("غضبان") || norm.contains("تخاصمت") || norm.contains("زعلان من") ->
                DailyChatReply(
                    text = "هدّئ روعك يا صديقي وصلِّ على النبي ﷺ؛ الغضب جمرة إذا استعجلنا معها ندمنا بعدها.\n\n" +
                        "إذا كنت واقفًا فاجلس، وتوضأ بماء بارد، ولا تأخذ أي قرار أو تكتب رسالة وأنت في لحظة انفعال. وإن كان خلافًا مع قريب أو صديق فالعفو والرفق يرفعان قدرك عند الله وعند الناس.",
                    domainTag = "دردشة أخوية يومية",
                    detectedTopic = "ضبط الغضب والإصلاح",
                    followUps = listOf("اكتب رسالة اعتذار وإصلاح ذات البين", "ما علاج الغضب في السنة؟")
                )

            // 9. التحيات الصرفة وتحية الصباح والمساء والجمعة والوداع
            isPureGreeting(norm) -> pureGreetingReply()

            norm.contains("صباح الخير") || norm.contains("صباح النور") || norm.contains("صباحكم") ->
                DailyChatReply(
                    text = "صباح الإيمان والرضا والرزق الواسع يا صاحبي! أصبحت وأصبح الملك لله.\nأسأل الله أن يفتح لك في يومك أبواب التوفيق والبهجة. وش ناوي تسوي اليوم؟",
                    domainTag = "ترحيب وتعريف",
                    detectedTopic = "تحية الصباح",
                    followUps = listOf("ما هي أذكار الصباح؟", "نسولف شوي")
                )

            norm.contains("مساء الخير") || norm.contains("مساء النور") || norm.contains("مسائكم") ->
                DailyChatReply(
                    text = "مساء السكينة والمودة يا غالي! أمسينا وأمسى الملك لله.\nعسى يومك كان طيبًا؟ لو حاب ندردش أو عندك سؤال قبل النوم أنا معك.",
