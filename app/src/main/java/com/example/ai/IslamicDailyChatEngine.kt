                        "كلنا نمرّ بأيام نحس فيها بملل أو ركود؛ لو حاب نسولف عن يومك كيف مشى، أو نحكي موقف خفيف يوسّع الصدر، أو تبغى خاطرة جميلة أو قصة ملهمة من سيرة الصالحين ترفع المعنويات — أنا جاهز وبكامل إنصاتي لك.\n\n" +
                        "قل لي: وش أكثر شيء شاغل بالك اليوم أو تحب نبدأ السالفة فيه؟",
