                    detectedTopic = "دردشة ودية بين صديقين",
                    followUps = listOf("اليوم كان متعب في الشغل", "احكِ لي قصة قصيرة ترفع المعنويات", "كيف أكسر الملل بطاعة لطيفة؟")
                )

            // 2. السؤال عن الحال والأخبار (رد صديق دافئ)
            norm.contains("كيف حالك") || norm.contains("كيفك") || norm.contains("اخبارك") ||
                norm.contains("شخبارك") || norm.contains("شلونك") || norm.contains("ازيك") ||
                norm.contains("عامل ايه") || norm.contains("وش علومك") ->
                DailyChatReply(
                    text = "أهلاً يا غالي! بخير وعافية ونعمة من الله ما دام أتواصل معك، الله يسعد قلبك.\n\n" +
                        "أنت طمني عنك وعن أهلك؟ كيف يومك ماشي معك اليوم — عساك مرتاح ومبسوط؟",
                    domainTag = "دردشة أخوية يومية",
                    detectedTopic = "السؤال عن الحال",
