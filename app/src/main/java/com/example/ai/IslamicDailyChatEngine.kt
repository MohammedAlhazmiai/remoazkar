package com.example.ai

/**
 * محرك التدريب اللغوي المحلي للدردشة اليومية والتفاعلات الودية والإيمانية (يعمل 100% بدون انترنت).
 * يوفر ردوداً فصيحة، حكيمة، ومطمئنة للاستفسارات والخواطر والتحيات اليومية.
 */
object IslamicDailyChatEngine {

    data class DailyChatReply(
        val text: String,
        val domainTag: String,
        val detectedTopic: String,
        val followUps: List<String>
    )

    fun matchDailyChat(query: String): DailyChatReply? {
        val norm = ArabicNlpEngine.normalize(query)

        return when {
            norm.contains("كيف حالك") || norm.contains("كيفك") || norm.contains("من أنت") || norm.contains("عرفني بنفسك") ->
                DailyChatReply(
                    text = "أنا مساعدك الإسلامي الذكي، أعمل محلياً وبدون إنترنت لخدمتك في العلوم الشرعية، الفتاوى، تفسير الأحلام، الخواطر، والدردشة اليومية الهادفة. قلبي وعقلي معك، فبم أستطيع مساعدتك اليوم؟",
                    domainTag = "دردشة واستدلال ديني",
                    detectedTopic = "التعريف بالمساعد",
                    followUps = listOf("ما هي الخدمات التي تقدمها؟", "اكتب لي دعاءً للمساء", "كيف أتوب من ذنب؟")
                )

            norm.contains("أشعر") && (norm.contains("ضيق") || norm.contains("حزن") || norm.contains("هم") || norm.contains("تعب") || norm.contains("قلق") || norm.contains("حيرة")) ->
                DailyChatReply(
                    text = "أسأل الله العظيم أن يفرج همك وشرح صدرك ويربط على قلبك.\n\n" +
                        "تذكر أخي الكريم قول الله تعالى: ﴿الَّذِينَ آمَنُوا وَتَطْمَئِنُّ قُلُوبُهُمْ بِذِكْرِ اللَّهِ ۗ أَلَا بِذِكْرِ اللَّهِ تَطْمَئِنُّ الْقُلُوبُ﴾ [الرعد: 28].\n" +
                        "وعليك بهذا الدعاء النبوي العظيم: «اللهم إني عبدك، وابن عبدك، وابن أمتك، ناصيتي بيدك، ماضٍ فيّ حكمك، عدلٌ فيّ قضاؤك...»\n\n" +
                        "خذ عُزلتك لركيعات في جوف الليل، واستغفر الله، فإن مع العسر يسراً.",
                    domainTag = "دردشة واستدلال ديني",
                    detectedTopic = "تفريج الهم والتشجيع الإيماني",
                    followUps = listOf("ما هو دعاء الكرب والفرج؟", "اكتب خاطرة إيمانية عن الصبر", "أريد أذكار الصباح والمساء")
                )

            norm.contains("شكرا") || norm.contains("جزاك الله خيرا") || norm.contains("بارك الله") ->
                DailyChatReply(
                    text = "وجزاك الله خيرًا وبارك فيك وفي أهلك ووقتك أخي الكريم، شكرًا لطيب كلماتك ودعائك.\n\nأنا في خدمتك دائمًا لصياغة الرسائل الدينية والخواطر والخطب والمحاضرات.",
                    domainTag = "شكر وثناء",
                    detectedTopic = "الرد على الشكر والثناء",
                    followUps = listOf("اكتب دعاءً شاملاً للخير", "ما فضائل الصدقة؟")
                )

            norm.contains("صباح الخير") || norm.contains("صباح النور") || norm.contains("صباحكم") ->
                DailyChatReply(
                    text = "صباح الإيمان والتقوى وبركة الرحمن! أصبحت وأصبح الملك لله، والحمد لله ولا إله إلا الله.\nنسأل الله أن يجعل يومك هذا مليئاً بالتوفيق والتيسير والعمل الصالح.",
                    domainTag = "ترحيب وتعريف",
                    detectedTopic = "تحية الصباح",
                    followUps = listOf("ما هي أذكار الصباح؟", "اكتب خاطرة عن التوكل في الصباح")
                )

            norm.contains("مساء الخير") || norm.contains("مساء النور") || norm.contains("مسائكم") ->
                DailyChatReply(
                    text = "مساء الرضا واليقين والمغفرة! أمسينا وأمسى الملك لله رب العالمين.\nأسأل الله أن يختم يومك بطاعة، وأن يكفيك شر كل ذي شر.",
                    domainTag = "ترحيب وتعريف",
                    detectedTopic = "تحية المساء",
                    followUps = listOf("ما هي أذكار المساء؟", "اكتب دعاء النوم والراحة")
                )

            norm.contains("نصيحة") || norm.contains("عظني") || norm.contains("ذكرني") || norm.contains("عظني موعظة") ->
                DailyChatReply(
                    text = "أوصيك بتقوى الله عز وجل سرّاً وعلانية، وحفظ لسانك، وكثرة الاستغفار.\n" +
                        "واعلم أن العبد لا يفلس أبداً ما دام لسانه رطباً بذكر الله، وأن أحب الأعمال إلى الله أدومها وإن قلّت.",
                    domainTag = "دردشة واستدلال ديني",
                    detectedTopic = "موعظة ونصيحة إيمانية",
                    followUps = listOf("ما هي أحب الأعمال إلى الله؟", "علمني سيد الاستغفار")
                )

            norm.contains("دعاء قصير") || norm.contains("دعاء") || norm.contains("أريد دعاء") ->
                DailyChatReply(
                    text = "«اللهم آتنا في الدنيا حسنة وفي الآخرة حسنة وقنا عذاب النار».\n" +
                        "و﴿رَبِّ اغْفِرْ لِي وَتُبْ عَلَيَّ إِنَّكَ أَنْتَ التَّوَّابُ الرَّحِيمُ﴾.\n" +
                        "و«اللهم إني أسألك الهدى والتُّقى والعفاف والغنى».",
                    domainTag = "دعاء مأثور",
                    detectedTopic = "أدعية نبوية قصيرة وجامعة",
                    followUps = listOf("ما هو دعاء الاستخارة؟", "اكتب لي دعاءً لقضاء الدين")
                )

            else -> null
        }
    }
}
