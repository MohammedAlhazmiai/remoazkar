            else -> null
        }
    }

    private fun isPureGreeting(norm: String): Boolean {
        val greetingWords = listOf(
            "مرحبا", "اهلا", "هلا", "اهلين", "يا هلا", "السلام عليكم", "سلام عليكم", "سلام"
        )
        return greetingWords.any { norm == it || norm.startsWith("$it ") } && norm.split(' ').size <= 6
    }

    private fun isThanksOrAppreciation(norm: String): Boolean =
        norm.contains("شكرا") || norm.contains("جزاك الله خيرا") || norm.contains("جزاك الله خير") ||
            norm.contains("بارك الله") || norm.contains("يعطيك العافيه") || norm.contains("مشكور") || norm == "تسلم"

    private fun pureGreetingReply(): DailyChatReply = DailyChatReply(
        text = "وعليكم السلام ورحمة الله وبركاته، يا أهلاً ومرحباً بك يا أخي وصديقي العزيز!\n\n" +
            "كيف حالك اليوم وعساك بخير؟ يسعدني جدًا صحبتك — سواء حاب ندردش ونسولف في شؤون يومك بروح أخوية، أو عندك سؤال فقهي، أو حلم تبغى تفسيره، أو تحب نكتب رسالة أو خطبة أو خاطرة.\n\n" +
            "تفضل، أنا كلي آذان صاغية لك!",
        domainTag = "ترحيب وتعريف",
        detectedTopic = "تحية وترحيب أخوي",
        followUps = listOf(
            "ماذا يمكنك أن تقدمه لي من مساعدة؟",
            "طفشان وأبغى ندردش شوي",
            "فسر لي حلمًا",
            "ما حكم صلاة المسافر؟"
        )
    )

